package s3id

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"strings"
	"testing"
)

var updateTable = flag.Bool("update", false, "rewrite docs/OPERATIONS_TABLE.md from the Go table")

const tablePath = "../../docs/OPERATIONS_TABLE.md"

// renderTable produces docs/OPERATIONS_TABLE.md from the Go table. The Go table is the single
// source of truth (docs/SPEC.md, S3 operation classifier); this file is a view of it.
func renderTable() []byte {
	var b bytes.Buffer
	b.WriteString("# S3 operations table\n\n")
	b.WriteString("<!-- GENERATED by internal/s3id (TestOperationsTableIsCurrent). Edit op.go and classify.go, then run\n")
	b.WriteString("     go test ./internal/s3id -run TestOperationsTableIsCurrent -update\n     Hand edits are overwritten. -->\n\n")
	b.WriteString("Reference: [Amazon S3 API operations](https://docs.aws.amazon.com/AmazonS3/latest/API/API_Operations_Amazon_Simple_Storage_Service.html), ")
	b.WriteString("fetched 2026-11-08 (116 operations; the page carries no version date). The Phase 0 reconciliation of every AWS name against this table, ")
	b.WriteString("with a reference link per operation, is `docs/reports/op-table-check-2026-11-08.md`.\n\n")
	fmt.Fprintf(&b, "The classifier is a pure, table-driven function `(method, shape, query keys, selected headers) → Operation`. "+
		"Rows are walked in order and the first match wins; `OPTIONS` at any level is `Preflight`; nothing matched is `Unknown` and is still proxied and counted. "+
		"`partNumber`, `versionId`, and `Range` are flags, never discriminators. `x-id` is a test oracle, never a discriminator.\n\n")
	fmt.Fprintf(&b, "**%d operations** (%d AWS names, plus `Unknown`, `Preflight`, and `PostObject`), **%d classifier rows**.\n\n", NumOps, NumOps-3, len(rules))

	b.WriteString("## Classes\n\n| Class | Operations |\n| --- | --- |\n")
	for c := Class(0); c < numClasses; c++ {
		var names []string
		for o := Op(0); o < opCount; o++ {
			if o.Class() == c {
				names = append(names, o.String())
			}
		}
		fmt.Fprintf(&b, "| `%s` | %s |\n", c, strings.Join(names, ", "))
	}

	b.WriteString("\n## Operations\n\nShape: `service` = no bucket; `bucket` = bucket, no key; `key` = bucket and key. Qualifier: query keys that must be present, `k=v` an exact value, `hdr:` a header that must be present.\n\n")
	b.WriteString("| Operation | Class | Rows (method · shape · qualifier) |\n| --- | --- | --- |\n")
	for o := Op(0); o < opCount; o++ {
		var rows []string
		if o == OpPreflight {
			rows = append(rows, "OPTIONS · any · —")
		}
		for _, r := range rules {
			if r.op == o {
				rows = append(rows, r.method+" · "+r.level.String()+" · "+qualifier(r))
			}
		}
		if o == OpUnknown {
			rows = append(rows, "any · any · nothing above matched")
		}
		fmt.Fprintf(&b, "| %s | `%s` | %s |\n", o, o.Class(), strings.Join(rows, "<br>"))
	}

	b.WriteString("\n## Classifier rows in precedence order\n\n| # | Method | Shape | Qualifier | Operation | Class |\n| --- | --- | --- | --- | --- | --- |\n")
	for i, r := range rules {
		fmt.Fprintf(&b, "| %d | %s | %s | %s | %s | `%s` |\n", i, r.method, r.level, qualifier(r), r.op, r.op.Class())
	}
	return b.Bytes()
}

func qualifier(r rule) string {
	var parts []string
	for _, k := range r.query {
		parts = append(parts, "`"+k+"`")
	}
	if r.value[0] != "" {
		parts = append(parts, "`"+r.value[0]+"="+r.value[1]+"`")
	}
	if r.header != "" {
		parts = append(parts, "`hdr:"+strings.ToLower(r.header)+"`")
	}
	if len(parts) == 0 {
		return "—"
	}
	return strings.Join(parts, " + ")
}

// TestOperationsTableIsCurrent fails when docs/OPERATIONS_TABLE.md drifts from the Go table.
func TestOperationsTableIsCurrent(t *testing.T) {
	want := renderTable()
	if *updateTable {
		if err := os.WriteFile(tablePath, want, 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s", tablePath)
		return
	}
	got, err := os.ReadFile(tablePath)
	if err != nil {
		t.Fatalf("%v (run with -update to generate)", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is out of date with the Go table; run: go test ./internal/s3id -run TestOperationsTableIsCurrent -update", tablePath)
	}
}
